frutas = ["maçã", "banana", "laranja", "uva"] # lista de frutas em um vetor cada fruta representa um elemento do vetor exemplo banana é 0
c = 0

while c < len(frutas):              # enquanto c for menor que o tamanho do vetor frutas | len(frutas) retorna o tamanho do vetor frutas
    print(frutas[c])                # imprime o elemento do vetor frutas na posição c
    c += 1                          # incrementa c em 1 para passar para o próximo elemento do vetor frutas
