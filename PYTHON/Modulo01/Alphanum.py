
a = input("digite algo:")

print(" que tipo de dado é esse? ", type(a))
print("é alfanumérico? ", a.isalnum())
print("é alfabético? ", a.isalpha())
print("é um número? ", a.isnumeric())
print("é decimal? ", a.isdecimal())
print("é um dígito? ", a.isdigit())
print("é um identificador? ", a.isidentifier())
print("é minúsculo? ", a.islower())
print("é maiúsculo? ", a.isupper())
print("é imprimível? ", a.isprintable())
print("é um espaço? ", a.isspace())
